export const MEDIA_CATALOG: readonly MediaCatalogEntry[] = MEDIA_SEEDS.map(defineMedia);

export const MEDIA_TITLES = MEDIA_CATALOG;

const MEDIA_BY_ID = new Map(MEDIA_CATALOG.map((entry) => [entry.id, entry]));

export function getMediaTitle(id: string): MediaCatalogEntry | undefined {
  return MEDIA_BY_ID.get(id);
}

export function listMediaTitles(targetLang = 'en'): readonly MediaCatalogEntry[] {
  const normalized = targetLang.trim().toLowerCase();
  return MEDIA_CATALOG.filter((entry) => entry.targetLang.trim().toLowerCase() === normalized);
}
