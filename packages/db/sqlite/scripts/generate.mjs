#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(here, '..');
const schemaPath = path.join(packageRoot, 'src', 'schema.sql');
const generatedDir = path.join(packageRoot, 'src', 'generated');
const outputPath = path.join(generatedDir, 'mirror.ts');

const sql = await readFile(schemaPath, 'utf8');
const checksum = createHash('sha256').update(sql).digest('hex');

function splitTopLevel(body) {
  const parts = [];
  let depth = 0;
  let current = '';
  let quote = null;
  for (const character of body) {
    if (quote) {
      current += character;
      if (character === quote) quote = null;
      continue;
    }
    if (character === "'") {
      quote = character;
      current += character;
      continue;
    }
    if (character === '(') depth += 1;
    if (character === ')') depth -= 1;
    if (character === ',' && depth === 0) {
      parts.push(current.trim());
      current = '';
      continue;
    }
    current += character;
  }
  if (current.trim().length > 0) parts.push(current.trim());
  return parts;
}

const tables = [];
const tablePattern = /CREATE TABLE IF NOT EXISTS\s+(\w+)\s*\(([\s\S]*?)\);/g;
for (const match of sql.matchAll(tablePattern)) {
  const name = match[1];
  const body = match[2] ?? '';
  const columns = [];
  for (const part of splitTopLevel(body)) {
    if (/^(UNIQUE|PRIMARY KEY|CHECK|FOREIGN KEY|CONSTRAINT)\b/i.test(part)) continue;
    const columnMatch = /^(\w+)\s+([A-Za-z]+)/.exec(part);
    if (!columnMatch) continue;
    columns.push({
      name: columnMatch[1],
      type: columnMatch[2].toLowerCase(),
    });
  }
  tables.push({ name, columns, indexes: [] });
}

const tableByName = new Map(tables.map((table) => [table.name, table]));
const indexPattern =
  /CREATE INDEX IF NOT EXISTS\s+(\w+)\s+ON\s+(\w+)\s*\(([^)]*)\)/g;
for (const match of sql.matchAll(indexPattern)) {
  const [, name, tableName, rawColumns] = match;
  const table = tableByName.get(tableName);
  if (!table) continue;
  table.indexes.push({
    name,
    columns: rawColumns.split(',').map((column) => column.trim()),
  });
}

const powerSyncSchema = { tables };

const source = `// Generated by pnpm sync:generate. Do not edit by hand.
export const MIRROR_SCHEMA_SHA256 = ${JSON.stringify(checksum)};

export const MIRROR_DDL = ${JSON.stringify(sql)};

export const MIRROR_TABLES = ${JSON.stringify(tables.map((table) => table.name))} as const;

export const POWERSYNC_SCHEMA = ${JSON.stringify(powerSyncSchema, null, 2)} as const;
`;

await mkdir(generatedDir, { recursive: true });
await writeFile(outputPath, source, 'utf8');
console.log(
  `mirror: ${tables.length} tables, checksum ${checksum.slice(0, 12)}… -> src/generated/mirror.ts`,
);
